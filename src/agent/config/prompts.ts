export type AIMode = 'analyst' | 'teacher';

// Ключевые слова для определения режима
const ANALYST_KEYWORDS = [
   'анализ', 'график', 'сигнал', 'call', 'put', 'вход',
   'прогноз', 'торгов', 'сделк', 'экспирац', 'уровн',
   'тренд', 'куда пойд', 'что думаешь', 'покажи', 'оцени',
   'лонг', 'шорт', 'стоп', 'тейк'
];

const TEACHER_KEYWORDS = [
   'научи', 'обуч', 'урок', 'объясни', 'расскажи',
   'как работает', 'что такое', 'не понимаю', 'задание',
   'начать обучение', 'продолжить', 'следующий урок'
];

export function detectAIMode(message: string, hasFiles: boolean): AIMode {
   const lowerMessage = message.toLowerCase();

   // Если есть файлы (изображения) - это анализ
   if (hasFiles) {
      return 'analyst';
   }

   // Подсчёт совпадений
   let analystScore = 0;
   let teacherScore = 0;

   ANALYST_KEYWORDS.forEach(keyword => {
      if (lowerMessage.includes(keyword)) analystScore++;
   });

   TEACHER_KEYWORDS.forEach(keyword => {
      if (lowerMessage.includes(keyword)) teacherScore++;
   });

   // Выбор режима
   if (analystScore > teacherScore) return 'analyst';
   if (teacherScore > analystScore) return 'teacher';

   // По умолчанию - учитель (для общих вопросов)
   return 'teacher';
}

/**
 * Собирает системный промпт: роль + правила рынка + общие правила.
 *
 * market === null означает «рынок не определён»: тогда в промпт уходят
 * правила всех трёх, и модель называет рынок сама в первой строке.
 */
export function buildPrompt(mode: AIMode, market: TradingMarket | null): string {
    const blocks = mode === 'analyst' ? ANALYST_MARKET : TEACHER_MARKET;
    const marketBlock = market ? blocks[market] : allMarketsBlock(blocks);

    return mode === 'analyst'
        ? [ANALYST_CORE, marketBlock, ANALYST_RULES].join('\n\n')
        : [TEACHER_CORE, marketBlock, TEACHER_RULES].join('\n\n');
}

/** Тот же промпт, но рынок берётся из выбора человека или из его вопроса. */
export function getPromptForMode(
    mode: AIMode,
    choice: MarketChoice = 'auto',
    message = '',
): string {
    return buildPrompt(mode, resolveMarket(choice, message));
}

