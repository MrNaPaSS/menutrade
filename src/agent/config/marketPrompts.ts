/**
 * Когда рынок неизвестен, отдаём правила всех трёх и просим определить
 * его самому. Это честнее, чем молча посчитать сделку по бинаркам.
 */
export function allMarketsBlock(blocks: Record<TradingMarket, string>): string {
    return [
        `### ❗ РЫНОК НЕ УКАЗАН

Определи рынок сам - по инструменту на графике, по терминалу или по
вопросу. В первой строке ответа скажи, с каким рынком работаешь, и
дальше следуй его правилам. Если понять невозможно - спроси одним
коротким вопросом, а не считай сделку наугад.`,
        blocks.binary,
        blocks.forex,
        blocks.crypto,
    ].join('\n\n');
}
